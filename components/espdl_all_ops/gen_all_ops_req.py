#!/usr/bin/env python3
"""Write an esp-dl compile_req.yml that requests every op and Conv kernel.

esp-dl compiles only the ops that components register (ESP-SR registers its
own short list). The face detection model registers none, so without this its
ops would be stripped and the model would fail to load at runtime. Reading
esp-dl's own catalogs keeps this in step with whatever esp-dl version is used.
"""
import argparse
import re


def top_level_keys(path, section):
    """Keys of a top-level mapping (`section:` followed by 2-space-indented keys)."""
    keys, inside = [], False
    for line in open(path, encoding="utf-8"):
        if re.match(r"^\S", line):
            inside = line.split("#")[0].strip() == section + ":"
            continue
        m = re.match(r"^  ([A-Za-z0-9_]+):\s*(#.*)?$", line)
        if inside and m:
            keys.append(m.group(1))
    return keys


def list_items(path, section):
    """Items of a top-level list (`section:` followed by `  - item` lines)."""
    items, inside = [], False
    for line in open(path, encoding="utf-8"):
        if re.match(r"^\S", line):
            inside = line.split("#")[0].strip() == section + ":"
            continue
        m = re.match(r"^  - ([A-Za-z0-9_]+)\s*(#.*)?$", line)
        if inside and m:
            items.append(m.group(1))
    return items


def scalar(path, key):
    for line in open(path, encoding="utf-8"):
        m = re.match(r"^%s:\s*(\d+)" % key, line)
        if m:
            return int(m.group(1))
    raise SystemExit("%s: no %s" % (path, key))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ops", required=True)
    ap.add_argument("--kernels", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    ops = top_level_keys(a.ops, "ops")
    kernels = list_items(a.kernels, "symbols")
    if not ops or not kernels:
        raise SystemExit("could not parse esp-dl op/kernel catalogs")
    lines = ["# Generated by gen_all_ops_req.py: every esp-dl op and kernel.",
             "kernel_abi: %d" % scalar(a.kernels, "kernel_abi"), "", "ops:"]
    lines += ["  - " + o for o in ops] + ["", "kernels:"] + ["  - " + k for k in kernels]
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("espdl_all_ops: %d ops, %d kernels" % (len(ops), len(kernels)))


if __name__ == "__main__":
    main()
